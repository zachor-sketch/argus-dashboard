export function failureCategory(error){
 const e=String(error);
 if(/HTTP_403|HTTP_429|SOURCE_BLOCKED/.test(e))return 'LEGITIMATE_403_ANTIBOT';
 if(/HTTP_404|ENOTFOUND|EAI_AGAIN/.test(e))return 'DNS_404';
 if(/TIMEOUT|ETIMEDOUT|aborted/i.test(e))return 'TIMEOUT';
 if(/PDF_REQUIRES/.test(e))return 'PDF_MANUAL_REVIEW_LIMITATION';
 if(/EXTERNAL_DOCUMENT_REQUIRES/.test(e))return 'EXTERNAL_DOCUMENT_MANUAL_REVIEW';
 if(/DISCOVERY_LIMIT/.test(e))return 'BOUNDED_DISCOVERY_BACKLOG';
 if(/NO_USABLE_IR_EVIDENCE/.test(e))return 'NO_USABLE_EVIDENCE';
 if(/PUBLICATION_DATE|NO_DATED/.test(e))return 'PUBLICATION_DATE_PARSING';
 if(/NO_REGULATORY_CONNECTOR/.test(e))return 'UNSUPPORTED_NON_US_REGULATORY_SOURCE';
 return 'OTHER';
}
